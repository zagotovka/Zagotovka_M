/*
 * cond_eval.h — вычислитель дополнительных условий срабатывания действий.
 *
 * Синтаксис (внутри строки действия после '?', либо в библиотеке условий):
 *   R<id>     - реле/устройство с ID id включено (GPIO-выход = 1);
 *               для PWM (topin 5) - dvalue > 0;
 *               для Zigbee (id >= NUMPIN) - состояние устройства.
 *   !R<id>    - реле выключено.
 *   RV<id>    - значение диммера (0..255/100), физический PWM или Zigbee.
 *   B<id>     - кнопка с ID id нажата (физическая или Zigbee-триггер).
 *   BU<id>    - кнопка НЕ нажата (синоним !B<id>).
 *   BH<id>    - кнопка удерживается (long-hold).
 *   T<id>[.n] - температура x10 (десятые градуса) датчика на пине id
 *               (DS18B20, n - номер датчика на шине; без .n - первый валидный;
 *               DHT22 - температура пина).
 *   H<id>     - влажность x10 DHT22 на пине id.
 *   C<n>      - ссылка на условие №n из библиотеки (Global Settings),
 *               n = 1..NUMCOND; для коротких полей (например "6:1?C3").
 *   Sr        - день (между восходом и закатом), Ss - ночь.
 *   <число>   - число, необязательно с одной десятичной цифрой ("25.5" = 255).
 *
 * Операторы: !  - НЕ,  &  - И,  |  - ИЛИ,  ( ) - скобки,
 *            =  равно,  >  больше,  <  меньше,
 *            g  больше или равно,  l  меньше или равно
 *            (также принимаются >= и <=).
 * Приоритет: ! > & > |.
 *
 * Трёхзначная логика (Клейни): если датчик не отвечает, его сравнение -
 * «неизвестно». «Неизвестное» проходит через !, & и | (Клейни: 0&x=0,
 * 1|x=1, иначе неизвестное распространяется) и в итоге БЛОКИРУЕТ действие:
 * !(T5<25) при мёртвом датчике НЕ включит обогрев. Обратная сторона:
 * явная истина через | перекрывает неизвестное - "T5<25|R1" сработает
 * при мёртвом T5, если R1 включено (ручной флаг сильнее датчика).
 *
 * Вложенность ссылок C<n>: работает цепочка из базового условия и ДВУХ
 * вложенных ссылок (C1 -> C2 -> операнды); третья вложенная ссылка
 * вычисляется как ложь (блок). Циклы C<n>, ссылающиеся сами на себя,
 * рвутся тем же guard'ом.
 *
 * Пример: BH1|(R1&!R2)|(RV5=255)
 *
 * Результат: cond_eval() возвращает true для пустого/NULL выражения.
 * Ошибка разбора -> false (действие блокируется) + лог не чаще 1 раза в 10 с.
 */

#ifndef INC_COND_EVAL_H_
#define INC_COND_EVAL_H_

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

/* Вычислить выражение. NULL/пустая строка -> true. */
bool cond_eval(const char *expr);

/* Вычислить условие из библиотеки условий SetSettings.conds[idx-1].
 * idx == 0 или вне диапазона -> true (условие не задано). */
bool cond_eval_ref(uint8_t idx);

/* Синтаксическая проверка выражения (без вычисления). */
bool cond_valid(const char *expr);

/* Инлайн-условия ('?...'), упоминающие id (R<id>, RV<id>, B<id>, BH<id>,
 * BU<id>, T<id>, H<id>), НЕ удаляются, а превращаются в заведомо ложные "?0":
 * действие перестаёт срабатывать, но не становится безусловным.
 * Возвращает число изменённых условий. */
int cond_strip_id(char *s, int id);

/* Записи библиотеки условий, упоминающие id, заменяются на заведомо ложное "0"
 * (очистка сделала бы все ссылки на них безусловными).
 * Возвращает true, если библиотека изменилась (нужно сохранить settings). */
bool cond_lib_neutralize_id(int id);

/* Подсчитать в строке инлайн-ссылки на библиотеку ("?C3", "C12"): для каждого
 * найденного номера n (1..NUMCOND) инкрементирует counts[n-1].
 * Используется для счётчика использования в UI. */
void cond_count_crefs(const char *s, int *counts);

#endif /* INC_COND_EVAL_H_ */
