
/*
 * cond_eval.h — вычислитель дополнительных условий срабатывания действий.
 *
 * Синтаксис (внутри строки действия после '?', либо в библиотеке условий):
 *   D<id>     - устройство с ID id включено: пин DEVICE (GPIO-выход = 1);
 *               для PWM (topin 5) - dvalue > 0;
 *               для Zigbee (id >= NUMPIN) - состояние устройства.
 *               Прежнее написание R<id> принимается так же (совместимость
 *               с условиями, сохранёнными до введения буквы D).
 *   !D<id>    - устройство выключено.
 *   DV<id>    - значение диммера (0..255/100), физический PWM или Zigbee
 *               (прежнее написание RV<id> тоже принимается).
 *   B<id>     - кнопка с ID id нажата (физическая или Zigbee-триггер).
 *   BU<id>    - кнопка НЕ нажата (синоним !B<id>).
 *   BH<id>    - кнопка удерживается (long-hold).
 *   T<id>[.n] - температура x10 (десятые градуса) датчика на пине id
 *               (DS18B20, n - номер датчика на шине; без .n - первый валидный;
 *               DHT22 - температура пина).
 *   H<id>     - влажность x10 DHT22 на пине id.
 *   C<n>      - ссылка на условие №n из библиотеки (Global Settings),
 *               n = 1..NUMCOND; для коротких полей (например "6:1?C3").
 *   Sr        - день (между восходом и закатом), Ss - ночь.
 *   <число>   - число, необязательно с одной десятичной цифрой ("25.5" = 255).
 *               Справа от знака сравнения допустим минус сразу перед цифрами:
 *               "T5<-5", "T5>-0.5", "T5g-12.3" (слева числа и минус не принимаются).
 *
 * Операторы: !  - НЕ,  &  - И,  |  - ИЛИ,  ( ) - скобки,
 *            =  равно,  >  больше,  <  меньше,
 *            g  больше или равно,  l  меньше или равно
 *            (также принимаются >= и <=).
 * Приоритет: ! > & > |.
 *
 * Трёхзначная логика (Клейни): если датчик не отвечает, его сравнение -
 * «неизвестно». «Неизвестное» проходит через !, & и | (Клейни: 0&x=0,
 * 1|x=1, иначе неизвестное распространяется) и в итоге БЛОКИРУЕТ действие:
 * !(T5<25) при мёртвом датчике НЕ включит обогрев. Обратная сторона:
 * явная истина через | перекрывает неизвестное - "T5<25|R1" сработает
 * при мёртвом T5, если R1 включено (ручной флаг сильнее датчика).
 *
 * Вложенность ссылок C<n>: работает цепочка из базового условия и ДВУХ
 * вложенных ссылок (C1 -> C2 -> операнды); третья вложенная ссылка
 * вычисляется как ложь (блок). Циклы C<n>, ссылающиеся сами на себя,
 * рвутся тем же guard'ом.
 *
 * Пример: BH1|(D1&!D2)|(DV5=255)
 *
 * Результат: cond_eval() возвращает true для пустого/NULL выражения.
 * Ошибка разбора -> false (действие блокируется) + лог не чаще 1 раза в 10 с.
 */

#ifndef INC_COND_EVAL_H_
#define INC_COND_EVAL_H_

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

/* Вычислить выражение. NULL/пустая строка -> true. */
bool cond_eval(const char *expr);

/* ─── Пул встроенных выражений (свободный ввод для Switch/Encoder/PID) ───
 *
 * Номер условия (uint8_t в dbPinToPin/dbPidConf) кодирует источник:
 *   0                      - условия нет (действие безусловно);
 *   1..NUMCOND             - ячейка библиотеки SetSettings.conds[] (старый
 *                            способ: номер выбирается из выпадающего списка);
 *   NUMCOND+1..NUMCOND+K   - слот встроенного пула: выражение введено
 *                            свободно на странице Switch/Encoder/PID.
 *
 * Индексы >= NUMCOND+1 старая прошивка трактует как "условия нет" (== true),
 * поэтому после отката прошивки условие перестаёт блокировать действие -
 * это единственный известный риск отката для данной схемы.
 */
#define COND_POOL_EXTRA 48     /* ёмкость пула: 48*COND_LEN = 2256 Б в .bss */
#define COND_POOL_TOTAL (NUMCOND + COND_POOL_EXTRA)
#define COND_IDX_NONE 0        /* условие не задано */
#define COND_IDX_INVALID 0xFF  /* длиннее COND_LEN / невалидно / нет места */

/* Вычислить условие по индексу: ячейка библиотеки (1..NUMCOND) либо слот
 * встроенного пула (NUMCOND+1..COND_POOL_TOTAL).
 * idx == 0 или вне диапазона -> true (условие не задано).
 * Пустая ячейка/пустой слот -> false (действие заблокировано). */
bool cond_eval_ref(uint8_t idx);

/* Поместить выражение во встроенный пул и вернуть его индекс.
 * "" -> COND_IDX_NONE. Дедупликация ТОЛЬКО внутри встроенного пула: совпадение
 * с ячейкой библиотеки намеренно НЕ склеивается, иначе правка ячейки в Global
 * Settings молча изменила бы условие связи.
 * COND_IDX_INVALID, если выражение длиннее COND_LEN-1, не проходит cond_valid()
 * либо в пуле нет свободного слота. */
uint8_t cond_intern(const char *expr);

/* Текст условия по индексу ("" если условия нет / индекс вне диапазона).
 * Указатель на слот пула действителен до следующего cond_intern()/gc. */
const char *cond_text(uint8_t idx);

/* Копия текста условия в буфер вызывающего - безопасно для JSON-эмиссии. */
void cond_text_copy(uint8_t idx, char *dst, size_t dstsz);

/* Освободить слоты пула, на которые никто не ссылается (ни одна связь
 * PinsLinks[] и ни один слот PID). Вызывается автоматически внутри
 * cond_intern перед выдачей нового слота. */
void cond_pool_gc(void);

/* Временно запретить GC (cond_intern при загрузке cond.ini с USB: ссылки из
 * pintopin.ini/pid.ini ещё не загружены, поэтому "неиспользуемым" выглядит
 * всё, и только что прочитанные выражения были бы выброшены). */
void cond_pool_freeze(bool on);

/* Занято/всего слотов пула (диагностика). */
int cond_pool_used(void);
int cond_pool_capacity(void);

/* Есть ли несохранённые изменения пула: cond_intern() создал новый слот или
 * cond_lib_neutralize_id() переписал выражение. Возвращает флаг и сбрасывает
 * его — вызывающий должен поставить в очередь USB сохранение cond.ini. */
bool cond_pool_take_dirty(void);

/* Полный сброс пула (перед загрузкой конфига с USB). */
void cond_pool_clear(void);

/* Синтаксическая проверка выражения (без вычисления). */
bool cond_valid(const char *expr);

/* Инлайн-условия ('?...'), упоминающие id (D<id>/R<id>, DV<id>/RV<id>, B<id>, BH<id>,
 * BU<id>, T<id>, H<id>), НЕ удаляются, а превращаются в заведомо ложные "?0":
 * действие перестаёт срабатывать, но не становится безусловным.
 * Возвращает число изменённых условий. */
int cond_strip_id(char *s, int id);

/* Записи библиотеки условий, упоминающие id, заменяются на заведомо ложное "0"
 * (очистка сделала бы все ссылки на них безусловными).
 * Возвращает true, если библиотека изменилась (нужно сохранить settings). */
bool cond_lib_neutralize_id(int id);

/* Подсчитать в строке инлайн-ссылки на библиотеку ("?C3", "C12"): для каждого
 * найденного номера n (1..NUMCOND) инкрементирует counts[n-1].
 * Используется для счётчика использования в UI. */
void cond_count_crefs(const char *s, int *counts);

#endif /* INC_COND_EVAL_H_ */

